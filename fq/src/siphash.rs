/// Number of compression rounds.
const C_ROUNDS: usize = 2;
/// Number of finalization rounds.
const D_ROUNDS: usize = 4;

/// Read a little-endian u64 from bytes.
#[inline(always)]
fn u8_to_u64_le(p: &[u8]) -> u64 {
    u64::from(p[0])
        | (u64::from(p[1]) << 8)
        | (u64::from(p[2]) << 16)
        | (u64::from(p[3]) << 24)
        | (u64::from(p[4]) << 32)
        | (u64::from(p[5]) << 40)
        | (u64::from(p[6]) << 48)
        | (u64::from(p[7]) << 56)
}

/// Write a little-endian u64 to bytes.
#[inline(always)]
fn u64_to_u8_le(p: &mut [u8], v: u64) {
    p[0] = v as u8;
    p[1] = (v >> 8) as u8;
    p[2] = (v >> 16) as u8;
    p[3] = (v >> 24) as u8;
    p[4] = (v >> 32) as u8;
    p[5] = (v >> 40) as u8;
    p[6] = (v >> 48) as u8;
    p[7] = (v >> 56) as u8;
}

/// One SipHash round.
#[inline(always)]
fn sipround(v0: &mut u64, v1: &mut u64, v2: &mut u64, v3: &mut u64) {
    *v0 = v0.wrapping_add(*v1);
    *v1 = v1.rotate_left(13);
    *v1 ^= *v0;
    *v0 = v0.rotate_left(32);
    *v2 = v2.wrapping_add(*v3);
    *v3 = v3.rotate_left(16);
    *v3 ^= *v2;
    *v0 = v0.wrapping_add(*v3);
    *v3 = v3.rotate_left(21);
    *v3 ^= *v0;
    *v2 = v2.wrapping_add(*v1);
    *v1 = v1.rotate_left(17);
    *v1 ^= *v2;
    *v2 = v2.rotate_left(32);
}

/// Compute SipHash-2-4.
///
/// # Arguments
/// * `input` - Input data to hash
/// * `key` - 16-byte key
///
/// # Returns
/// 8-byte hash output
pub fn hash(input: &[u8], key: &[u8; 16]) -> [u8; 8] {
    let mut out = [0u8; 8];
    siphash_into(input, key, &mut out);
    out
}

/// Compute SipHash-2-4 with configurable output length.
///
/// # Arguments
/// * `input` - Input data to hash
/// * `key` - 16-byte key
/// * `out` - Output buffer (must be 8 or 16 bytes)
pub fn siphash_into(input: &[u8], key: &[u8; 16], out: &mut [u8]) {
    debug_assert!(out.len() == 8 || out.len() == 16);

    let mut v0: u64 = 0x736f6d6570736575;
    let mut v1: u64 = 0x646f72616e646f6d;
    let mut v2: u64 = 0x6c7967656e657261;
    let mut v3: u64 = 0x7465646279746573;

    let k0 = u8_to_u64_le(&key[0..8]);
    let k1 = u8_to_u64_le(&key[8..16]);

    v3 ^= k1;
    v2 ^= k0;
    v1 ^= k1;
    v0 ^= k0;

    if out.len() == 16 {
        v1 ^= 0xee;
    }

    // Process full 8-byte blocks
    let mut pos = 0;
    while pos + 8 <= input.len() {
        let m = u8_to_u64_le(&input[pos..pos + 8]);
        v3 ^= m;

        for _ in 0..C_ROUNDS {
            sipround(&mut v0, &mut v1, &mut v2, &mut v3);
        }

        v0 ^= m;
        pos += 8;
    }

    // Process remaining bytes
    let left = input.len() - pos;
    let mut b = (input.len() as u64) << 56;

    // Accumulate remaining bytes
    if left >= 7 {
        b |= u64::from(input[pos + 6]) << 48;
    }
    if left >= 6 {
        b |= u64::from(input[pos + 5]) << 40;
    }
    if left >= 5 {
        b |= u64::from(input[pos + 4]) << 32;
    }
    if left >= 4 {
        b |= u64::from(input[pos + 3]) << 24;
    }
    if left >= 3 {
        b |= u64::from(input[pos + 2]) << 16;
    }
    if left >= 2 {
        b |= u64::from(input[pos + 1]) << 8;
    }
    if left >= 1 {
        b |= u64::from(input[pos]);
    }

    v3 ^= b;

    for _ in 0..C_ROUNDS {
        sipround(&mut v0, &mut v1, &mut v2, &mut v3);
    }

    v0 ^= b;

    if out.len() == 16 {
        v2 ^= 0xee;
    } else {
        v2 ^= 0xff;
    }

    for _ in 0..D_ROUNDS {
        sipround(&mut v0, &mut v1, &mut v2, &mut v3);
    }

    let hash = v0 ^ v1 ^ v2 ^ v3;
    u64_to_u8_le(&mut out[0..8], hash);

    if out.len() == 8 {
        return;
    }

    // 16-byte output
    v1 ^= 0xdd;

    for _ in 0..D_ROUNDS {
        sipround(&mut v0, &mut v1, &mut v2, &mut v3);
    }

    let hash = v0 ^ v1 ^ v2 ^ v3;
    u64_to_u8_le(&mut out[8..16], hash);
}

/// Convenience function returning hash as u64.
///
/// This matches the `picohash_siphash` API from picoquic.
pub fn hash_u64(input: &[u8], key: &[u8; 16]) -> u64 {
    let out = hash(input, key);
    u8_to_u64_le(&out)
}

